"""React + TypeScript + Vite Project Scaffolding Engine.

Enables DevPilot AI to build complete, runnable, production-ready software
applications from scratch when an empty repository is connected.
"""

import json
from pathlib import Path
from typing import Dict, Any, List


class ReactViteScaffolder:
    """Scaffolds a modern, production-grade React 19 + TypeScript + Vite project."""

    def scaffold_project(
        self,
        sandbox_path: Path,
        requirement_prompt: str = "Build a responsive login page",
        app_title: str = "DevPilot Autonomous Application",
    ) -> Dict[str, Any]:
        """Creates the full project file tree inside the sandbox directory.

        Args:
            sandbox_path: Absolute Path to the sandbox directory.
            requirement_prompt: Natural language specification.
            app_title: Display title for the application.

        Returns:
            Dictionary with created files and metadata.
        """
        sandbox_path = Path(sandbox_path).resolve()
        sandbox_path.mkdir(parents=True, exist_ok=True)

        created_files: List[str] = []

        # 1. package.json
        pkg_json_content = self._generate_package_json(app_title)
        pkg_path = sandbox_path / "package.json"
        pkg_path.write_text(json.dumps(pkg_json_content, indent=2), encoding="utf-8")
        created_files.append("package.json")

        # 2. tsconfig.json & tsconfig.node.json
        ts_config = self._generate_tsconfig()
        (sandbox_path / "tsconfig.json").write_text(json.dumps(ts_config, indent=2), encoding="utf-8")
        created_files.append("tsconfig.json")

        ts_node_config = self._generate_tsconfig_node()
        (sandbox_path / "tsconfig.node.json").write_text(json.dumps(ts_node_config, indent=2), encoding="utf-8")
        created_files.append("tsconfig.node.json")

        # 3. vite.config.ts
        vite_config = self._generate_vite_config()
        (sandbox_path / "vite.config.ts").write_text(vite_config, encoding="utf-8")
        created_files.append("vite.config.ts")

        # 4. index.html
        index_html = self._generate_index_html(app_title)
        (sandbox_path / "index.html").write_text(index_html, encoding="utf-8")
        created_files.append("index.html")

        # 5. src/ directory structure
        src_dir = sandbox_path / "src"
        src_dir.mkdir(parents=True, exist_ok=True)

        pages_dir = src_dir / "pages"
        pages_dir.mkdir(parents=True, exist_ok=True)

        # 6. src/main.tsx
        main_tsx = self._generate_main_tsx()
        (src_dir / "main.tsx").write_text(main_tsx, encoding="utf-8")
        created_files.append("src/main.tsx")

        # 7. src/index.css
        index_css = self._generate_index_css()
        (src_dir / "index.css").write_text(index_css, encoding="utf-8")
        created_files.append("src/index.css")

        # 8. src/pages/LoginPage.tsx
        login_tsx = self._generate_login_page_tsx()
        (pages_dir / "LoginPage.tsx").write_text(login_tsx, encoding="utf-8")
        created_files.append("src/pages/LoginPage.tsx")

        # 9. src/App.tsx
        app_tsx = self._generate_app_tsx()
        (src_dir / "App.tsx").write_text(app_tsx, encoding="utf-8")
        created_files.append("src/App.tsx")

        # 10. tests/ directory structure & automated tests
        tests_dir = sandbox_path / "tests"
        tests_dir.mkdir(parents=True, exist_ok=True)

        # Standalone Node test runner verifying all 6 functional criteria
        login_test_mjs = self._generate_node_test_runner()
        (tests_dir / "login.test.mjs").write_text(login_test_mjs, encoding="utf-8")
        created_files.append("tests/login.test.mjs")

        # Vitest / React Testing Library integration test
        login_test_tsx = self._generate_vitest_test()
        (pages_dir / "LoginPage.test.tsx").write_text(login_test_tsx, encoding="utf-8")
        created_files.append("src/pages/LoginPage.test.tsx")

        return {
            "success": True,
            "created_files": created_files,
            "entrypoint": "src/pages/LoginPage.tsx",
            "app_title": app_title,
        }

