"""Pydantic schemas for Work Breakdown Structure and Execution Plans."""

from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional, Literal
from pydantic import BaseModel, Field


class TaskStatus(str, Enum):
    PENDING = "pending"
    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    FAILED = "failed"
    BLOCKED = "blocked"


class TaskFramework(str, Enum):
    CREWAI = "crewai"
    GOOGLE_ADK = "google_adk"
    SYSTEM_GATE = "system_gate"


class TaskItem(BaseModel):
    """An individual atomic task in the execution plan."""
    id: str = Field(..., description="Unique task id, e.g. TSK-01")
    title: str = Field(..., description="Short task title")
    description: str = Field(..., description="Actionable instruction for the agent")
    assigned_framework: TaskFramework = Field(
        ...,
        description="Whether this task executes via CrewAI or Google ADK"
    )
    assigned_role: str = Field(
        ...,
        description="Agent role name, e.g., Planner, Coder, TestGenerator, Debugger, Auditor"
    )
    dependencies: List[str] = Field(
        default_factory=list,
        description="List of task IDs that must complete before this task begins"
    )
    status: TaskStatus = Field(default=TaskStatus.PENDING)
    output_summary: Optional[str] = Field(default=None)
    started_at: Optional[datetime] = None
    completed_at: Optional[datetime] = None


class ExecutionPlan(BaseModel):
    """Full execution plan generated by the CrewAI Planner/Manager Agent."""
    plan_id: str = Field(default_factory=lambda: f"PLAN-{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}")
    requirement_id: str
    strategy_summary: str = Field(..., description="High-level architectural execution strategy")
    tasks: List[TaskItem] = Field(default_factory=list)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    current_task_index: int = 0
    is_completed: bool = False
    replan_count: int = Field(default=0, description="Number of times re-planning was triggered due to test failure")

