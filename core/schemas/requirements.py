"""Pydantic schemas for Developer Requirements and Analysis."""

from datetime import datetime, timezone
from typing import List, Optional
from pydantic import BaseModel, Field
from core.schemas.repository import RepositoryConfig


class AcceptanceCriterion(BaseModel):
    """Specific measurable acceptance criterion."""
    id: str = Field(..., description="Unique criterion identifier, e.g. AC-1")
    description: str = Field(..., description="Detailed condition that must be met")
    verification_method: str = Field(
        default="automated_unit_test",
        description="Method used to verify this criterion (e.g., automated_unit_test, static_analysis)"
    )
    passed: Optional[bool] = Field(default=None, description="Whether this criterion was verified as passing")


class DeveloperRequirement(BaseModel):
    """Raw requirement submitted by developer or user."""
    id: str = Field(default_factory=lambda: f"REQ-{datetime.now(timezone.utc).strftime('%Y%m%d%H%M%S')}")
    raw_prompt: str = Field(..., min_length=5, description="Raw input text submitted by developer")
    target_repo_path: str = Field(
        default="sandbox_workspace/sample_repo",
        description="Relative or absolute path to the target repository"
    )
    repo_config: Optional[RepositoryConfig] = Field(
        default=None,
        description="Optional structured repository configuration"
    )
    submitted_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    metadata: dict = Field(default_factory=dict, description="Optional metadata or tags")


class RequirementAnalysis(BaseModel):
    """Structured decomposition and analysis generated by Manager/Planner Agent."""
    requirement_id: str = Field(default="", description="Correlating requirement ID")
    title: str = Field(..., description="Concise summary title of the requirement")
    problem_statement: str = Field(..., description="Clear explanation of the problem or feature requested")
    feature_category: str = Field(
        default="feature_addition",
        description="Category: bug_fix, feature_addition, refactoring, performance_optimization"
    )
    acceptance_criteria: List[AcceptanceCriterion] = Field(default_factory=list)
    architectural_impact: str = Field(default="", description="Summary of modules or classes affected")
    estimated_complexity: str = Field(default="Medium", description="Low, Medium, or High")
    prerequisites: List[str] = Field(default_factory=list)

